const originalText = new WeakMap();
const originalAttributes = new WeakMap();
let observer;

export function getLanguagePreference() {
  const saved = localStorage.getItem(STORAGE_KEY) || "system";
  return SUPPORTED.has(saved) ? saved : "system";
}

export function getResolvedLanguage(preference = getLanguagePreference()) {
  if (preference === "en" || preference === "de") return preference;
  return (navigator.languages || [navigator.language || "en"]).some((language) => /^de(?:-|$)/i.test(language)) ? "de" : "en";
}

export function getLocale() {
  return getResolvedLanguage() === "de" ? "de-DE" : "en-US";
}

export function setLanguage(preference) {
  const selected = SUPPORTED.has(preference) ? preference : "system";
  localStorage.setItem(STORAGE_KEY, selected);
  document.documentElement.lang = getResolvedLanguage(selected);
  translateDocument();
  window.dispatchEvent(new CustomEvent("nimbuslanguagechange", { detail: { preference: selected, language: getResolvedLanguage(selected) } }));
}

export function cycleLanguage() {
  const order = ["system", "en", "de"];
  setLanguage(order[(order.indexOf(getLanguagePreference()) + 1) % order.length]);
}

