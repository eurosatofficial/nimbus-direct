export function translateText(input, language = getResolvedLanguage()) {
  const value = String(input ?? "");
  if (language !== "de" || !value.trim()) return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const clean = value.trim();
  let translated = de[clean];
  if (!translated) translated = translatePlural(clean);
  if (!translated) {
    const relative = clean.match(/^(\d+)([smhd]) ago$/);
    if (relative) translated = `vor ${relative[1]}${relative[2] === "d" ? " T" : relative[2] === "h" ? " Std." : relative[2] === "m" ? " Min." : " Sek."}`;
  }
  if (!translated && clean.startsWith("Updated ")) translated = `Aktualisiert ${clean.slice(8)}`;
  if (!translated && clean.startsWith("Created ")) translated = `Erstellt ${clean.slice(8)}`;
  if (!translated && clean.startsWith("Last active ")) translated = `Zuletzt aktiv ${clean.slice(12).replace(" · Expires ", " · Läuft ab ")}`;
  if (!translated && clean.startsWith("Expires ")) translated = `Läuft ab ${clean.slice(8)}`;
  if (!translated && clean.startsWith("Loading ")) translated = `${clean.slice(8)} wird geladen`;
  if (!translated) {
    const stateCount = clean.match(/^(\d+)\s+(running|stopped|suspended)$/);
    if (stateCount) translated = `${stateCount[1]} ${de[stateCount[2]]}`;
  }
  if (!translated) {
    const acrossClusters = clean.match(/^Across\s+(\d+)\s+clusters?$/);
    if (acrossClusters) translated = `In ${acrossClusters[1]} ${Number(acrossClusters[1]) === 1 ? "Cluster" : "Clustern"}`;
  }
  if (!translated && clean.endsWith(" uptime")) translated = `${clean.slice(0, -7)} Betriebszeit`;
  if (!translated && clean.endsWith(" waiting")) translated = `${clean.slice(0, -8)} wartend`;
  if (!translated && clean.startsWith("Generated ")) translated = `Erstellt ${clean.slice(10)}`;
  if (!translated && clean.startsWith("Health sampled ")) translated = `Zustand erfasst ${clean.slice(15)}`;
  if (!translated) {
    const coverage = clean.match(/^(\d+)% of active accounts use 2FA$/);
    if (coverage) translated = `${coverage[1]} % der aktiven Konten verwenden 2FA`;
  }
  if (!translated) {
    const protectedAccounts = clean.match(/^(\d+) of (\d+) protected$/);
    if (protectedAccounts) translated = `${protectedAccounts[1]} von ${protectedAccounts[2]} geschützt`;
  }
  if (!translated) {
    const protectedTotal = clean.match(/^of (\d+) protected$/);
    if (protectedTotal) translated = `von ${protectedTotal[1]} geschützt`;
  }
  if (!translated && clean.startsWith("of ")) translated = `von ${clean.slice(3)}`;
  if (!translated) {
    const capacity = clean.match(/^(.+)\s+of\s+(.+)$/);
    if (capacity) translated = `${capacity[1]} von ${capacity[2]}`;
  }
  if (!translated) {
    const taskState = clean.match(/^(\d+)\s+failed tasks?\s+·\s+(\d+)\s+stuck$/);
    if (taskState) translated = `${taskState[1]} fehlgeschlagene Aufgaben · ${taskState[2]} festgefahren`;
  }
  if (!translated) {
    const online = clean.match(/^(\d+)\s*\/\s*(\d+)\s+online$/);
    if (online) translated = `${online[1]} / ${online[2]} online`;
  }
  if (!translated) {
    const coverage = clean.match(/^(\d+)\s+nodes? metrics\s+·\s+(\d+)\s+storage paths?$/);
    if (coverage) translated = `Metriken von ${coverage[1]} Knoten · ${coverage[2]} Speicherpfade`;
  }
  if (!translated) {
    const paths = clean.match(/^(\d+)\s+storage paths?$/);
    if (paths) translated = `${paths[1]} Speicherpfade`;
  }
  if (!translated) {
    const total = clean.match(/^(\d+)\s+total$/);
    if (total) translated = `${total[1]} insgesamt`;
  }
  if (!translated) {
    const storage = clean.match(/^(.+)\s+available\s+·\s+(.+)\s+total$/);
    if (storage) translated = `${storage[1]} verfügbar · ${storage[2]} gesamt`;
  }
  if (!translated && clean.includes(" · Last active ")) {
    translated = clean.replace(" · Last active ", " · Zuletzt aktiv ").replace(" · Expires ", " · Läuft ab ");
    translated = translated.replace(/(\d+)([smhd]) ago/g, (_, amount, unit) => `vor ${amount}${unit === "d" ? " T" : unit === "h" ? " Std." : unit === "m" ? " Min." : " Sek."}`);
  }
  if (!translated) {
    const client = clean.match(/^(.+) on (macOS|iOS|iPadOS|Android|Windows|Linux)$/);
    if (client) translated = `${client[1]} unter ${client[2]}`;
  }
  if (!translated && /\bcores?\b/.test(clean)) translated = clean.replace(/\b(\d+) cores?\b/g, "$1 Kerne");
  if (!translated && clean.startsWith("Appearance: ")) translated = `Darstellung: ${de[clean.slice(12)] || clean.slice(12)}`;
  if (!translated && clean.startsWith("Language: ")) translated = `Sprache: ${de[clean.slice(10)] || clean.slice(10)}`;
  return translated ? `${leading}${translated}${trailing}` : value;
}

export function t(source, replacements = {}) {
  let value = translateText(source);
  Object.entries(replacements).forEach(([key, replacement]) => { value = value.replaceAll(`{${key}}`, String(replacement)); });
  return value;
}

function shouldSkip(node) {
  const parent = node.nodeType === Node.TEXT_NODE ? node.parentElement : node;
  return !parent || parent.closest("script, style, code, pre, [data-no-i18n]");
}

function translateTextNode(node) {
  if (shouldSkip(node)) return;
  if (!originalText.has(node)) originalText.set(node, node.nodeValue);
  const source = originalText.get(node);
  node.nodeValue = getResolvedLanguage() === "de" ? translateText(source, "de") : source;
}

function translateElementAttributes(element) {
  if (!(element instanceof Element) || shouldSkip(element)) return;
  const attributes = ["placeholder", "aria-label", "title"];
  let saved = originalAttributes.get(element);
  if (!saved) {
    saved = new Map();
    originalAttributes.set(element, saved);
  }
  attributes.forEach((name) => {
    if (!element.hasAttribute(name)) return;
    if (!saved.has(name)) saved.set(name, element.getAttribute(name));
    const source = saved.get(name);
    element.setAttribute(name, getResolvedLanguage() === "de" ? translateText(source, "de") : source);
  });
}

function translateRoot(root) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root);
    return;
  }
  if (!(root instanceof Element || root instanceof Document)) return;
  if (root instanceof Element) translateElementAttributes(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    if (walker.currentNode.nodeType === Node.TEXT_NODE) translateTextNode(walker.currentNode);
    else translateElementAttributes(walker.currentNode);
  }
}

function observe() {
  if (!observer) return;
  observer.observe(document.documentElement, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["placeholder", "aria-label", "title"] });
}

export function translateDocument() {
  observer?.disconnect();
  document.documentElement.lang = getResolvedLanguage();
  translateRoot(document);
  observe();
}

export function installTranslationObserver() {
  if (observer) return;
  observer = new MutationObserver((mutations) => {
    observer.disconnect();
    mutations.forEach((mutation) => {
      if (mutation.type === "characterData") {
        originalText.set(mutation.target, mutation.target.nodeValue);
        translateTextNode(mutation.target);
      } else if (mutation.type === "attributes") {
        const saved = originalAttributes.get(mutation.target) || new Map();
        saved.set(mutation.attributeName, mutation.target.getAttribute(mutation.attributeName));
        originalAttributes.set(mutation.target, saved);
        translateElementAttributes(mutation.target);
      } else {
        mutation.addedNodes.forEach(translateRoot);
      }
    });
    observe();
  });
  translateDocument();
}

